"""Generated `docs/product_insights.md` (Phase 4.6).

Pure functions: plain dicts/lists in, markdown out. Every number in the document comes from
the run's tables (gold.product_segments, gold.product_associations, the MLflow runs) via the
notebook; nothing is typed by hand, so the document can't drift from the data.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence


def _pct(v) -> str:
    return "–" if v is None else f"{100 * v:.1f}%"


def _num(v, digits: int = 1) -> str:
    return "–" if v is None else f"{v:,.{digits}f}"


def _int(v) -> str:
    return "–" if v is None else f"{int(v):,}"


def dedupe_pairs(rules: Sequence[Mapping], n: int) -> list[dict]:
    """Keep the first rule of each unordered item set (A -> B and B -> A are one pair: the
    first in the given order wins), and at most one rule per antecedent. Returns n rules."""
    seen_sets, seen_antecedents, out = set(), set(), []
    for r in rules:
        items = frozenset([*r["antecedent"], r["consequent"]])
        ante = tuple(r["antecedent"])
        if items in seen_sets or ante in seen_antecedents:
            continue
        seen_sets.add(items)
        seen_antecedents.add(ante)
        out.append(dict(r))
        if len(out) == n:
            break
    return out


def recommendation(rule: Mapping) -> str:
    """One rule as a cross-sell sentence (numbers from the rule itself)."""
    return (
        f"Basket has **{rule['antecedent_descriptions']}** → suggest "
        f"**{rule['consequent_description']}**: already in {_pct(rule['confidence'])} of those "
        f"baskets, {rule['lift']:.1f}× more likely than in an average basket "
        f"({_int(rule['baskets_with_rule'])} orders)."
    )


def _rule_table(rules: Sequence[Mapping]) -> list[str]:
    lines = [
        "| If the basket has | Recommend | Support | Confidence | Lift | Orders |",
        "|---|---|---|---|---|---|",
    ]
    for r in rules:
        lines.append(
            f"| {r['antecedent_descriptions']} | {r['consequent_description']} | "
            f"{_pct(r['support'])} | {_pct(r['confidence'])} | {r['lift']:.1f} | "
            f"{_int(r['baskets_with_rule'])} |"
        )
    return lines


def render_product_insights_md(
    *,
    as_of,
    n_products: int,
    segment_rows: Sequence[Mapping],
    group_rows: Sequence[Mapping],
    playbook: Mapping[str, Mapping[str, str]],
    segment_descriptions: Mapping[str, str],
    model_facts: Mapping[str, str],
    mba_facts: Mapping[str, str],
    rule_counts: Sequence[Mapping],
    market_overlap: Mapping[str, int],
    top_complementary: Sequence[Mapping],
    top_range: Sequence[Mapping],
    top_basket: Sequence[Mapping],
    top_rest_only: Sequence[Mapping],
    frequent_products: int,
    caveats: Sequence[str],
    images: Mapping[str, str],
) -> str:
    seg = {r["segment_name"]: r for r in segment_rows}
    counts = {(r["scope"], r["rule_type"]): r for r in rule_counts}

    def rec(scope, rtype):
        return int((counts.get((scope, rtype)) or {}).get("recommendable") or 0)

    rec_all = rec("all", "similar") + rec("all", "complementary")
    core = seg.get("Core Fast Movers", {})
    fading = seg.get("Fading Lines", {})
    tail = seg.get("Long Tail", {})

    lines = [
        "# Product segments and cross-sell insights",
        "",
        f"Snapshot **{as_of}** · {n_products:,} products · generated by "
        "`notebooks/04_product_segmentation_mba.py` (section 7) from the real run; do not "
        "edit by hand.",
        "",
        "## Key insights",
        "",
        f"1. **Revenue is concentrated in the Core range.** Core Fast Movers are "
        f"{_pct(core.get('product_share'))} of products but {_pct(core.get('revenue_share'))} "
        f"of revenue; they sell in a median {_pct(core.get('median_active_week_share'))} of weeks.",
        f"2. **A fifth of the catalogue has stopped selling.** Fading Lines are "
        f"{_pct(fading.get('product_share'))} of products (median "
        f"{_int(fading.get('median_days_since_last_sale'))} days since the last sale) for "
        f"{_pct(fading.get('revenue_share'))} of revenue: candidates for clearance and delisting.",
        f"3. **The long tail is large but worth little.** {_pct(tail.get('product_share'))} of "
        f"products had fewer than 20 orders and made {_pct(tail.get('revenue_share'))} of revenue.",
        f"4. **Customers buy collections.** Of {rec_all:,} recommendable rules in all baskets, "
        f"{rec('all', 'similar'):,} link items of the same range (other designs or companion "
        f"pieces) and {rec('all', 'complementary'):,} link different products. Colour/design "
        f"variants ({_int((counts.get(('all', 'variant')) or {}).get('rules'))} rules) were "
        "excluded as trivial.",
        f"5. **Only {frequent_products:,} products ({_pct(frequent_products / n_products)}) are "
        "bought often enough for item-level rules**; the rest need segment-level "
        "recommendations (e.g. Core best-sellers).",
        f"6. **Markets differ.** {market_overlap.get('in_both', 0):,} rules hold in both the UK "
        f"and the rest of the world; {market_overlap.get('rest_only', 0):,} appear only abroad "
        "(smaller sample, see caveats).",
        "",
        "## How it was built",
        "",
        "**Product segmentation**",
        "",
    ]
    lines += [f"- **{k}**: {v}" for k, v in model_facts.items()]
    lines += ["", "**Market basket analysis**", ""]
    lines += [f"- **{k}**: {v}" for k, v in mba_facts.items()]

    lines += [
        "",
        "## Product segments",
        "",
        "| Segment | Products | Share of products | Share of revenue | Median units/week | "
        "Median share of weeks sold | Median price | Median days since last sale | Median Q4 share |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in segment_rows:
        lines.append(
            f"| {r['segment_name']} | {_int(r['products'])} | {_pct(r['product_share'])} | "
            f"{_pct(r['revenue_share'])} | {_num(r['median_units_per_week'])} | "
            f"{_pct(r['median_active_week_share'])} | £{_num(r['median_price'], 2)} | "
            f"{_int(r['median_days_since_last_sale'])} | {_pct(r['median_q4_share'])} |"
        )
    lines.append("")
    for name, desc in segment_descriptions.items():
        lines.append(f"- **{name}**: {desc}")

    lines += [
        "",
        "## Action groups and recommended actions",
        "",
        "| Segment | Action group | Products | Share of revenue | Recommended action | KPI |",
        "|---|---|---|---|---|---|",
    ]
    for g in group_rows:
        play = playbook[g["action_group"]]
        lines.append(
            f"| {g['segment_name']} | {g['action_group']} | {_int(g['products'])} | "
            f"{_pct(g['revenue_share'])} | {play['action']} | {play['kpi']} |"
        )

    lines += ["", "## Association rules", "", "| Scope | Rule type | Rules | Recommendable | Median lift | Median confidence |", "|---|---|---|---|---|---|"]  # fmt: skip
    for r in rule_counts:
        lines.append(
            f"| {r['scope']} | {r['rule_type']} | {_int(r['rules'])} | "
            f"{_int(r['recommendable'])} | {_num(r['median_lift'], 2)} | "
            f"{_pct(r['median_confidence'])} |"
        )

    sections = [
        (
            "Cross-sell: different products bought together",
            "Product-page recommendations across product types (rule type *complementary*, "
            "one rule per pair, by lift).",
            top_complementary,
        ),
        (
            "Complete the collection",
            "Same range, other design or companion piece (rule type *similar*, one rule per "
            "pair, by confidence): show the rest of the range next to the item.",
            top_range,
        ),
        (
            "Basket completion",
            "Two or more items already in the basket (by confidence): checkout prompts.",
            top_basket,
        ),
        (
            "Rest of the world only",
            "Rules mined in non-UK baskets that don't hold in the UK (by lift); each rests on "
            "a small number of orders, so test before rolling out.",
            top_rest_only,
        ),
    ]
    for title, intro, rules in sections:
        lines += ["", f"### {title}", "", intro, ""]
        if not rules:
            lines.append("_No rules in this group._")
            continue
        lines += _rule_table(rules)
        lines += ["", "Recommendations:", ""]
        lines += [f"- {recommendation(r)}" for r in rules[:5]]

    lines += ["", "## Caveats", ""] + [f"- {c}" for c in caveats]
    for title, path in images.items():
        lines += ["", f"![{title}]({path})"]
    lines.append("")
    return "\n".join(lines)
